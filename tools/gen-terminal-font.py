#!/usr/bin/env python3
"""Regenerate the inlined terminal font in web/shell.html.

The browser build draws into xterm.js, which takes its cell from the font. The
raster assumes a cell is two square pixels stacked (width/height 0.5), and
ball sprites in `--glyphs sextant` need U+1FB00-1FB3B, which xterm doesn't
draw itself (it does draw the quadrant blocks, via customGlyphs). Left to the
platform, macOS gets Menlo (no sextants) and other systems something else, so
the page looks different everywhere. Bundling a face fixes the first; the
shell's squareCells() fixes the cell, whatever the font.

Every face in FACES is bundled, and the page picks one with ?font=<key>. Three
finalists were playtested (2026-10-22), all with the full sextant block that
--glyphs sextant needs: Iosevka Term Extended (the default), Cascadia Mono and
Unscii 16. Fairfax HD, xsofy's face, is kept for fun. A face missing a few UI
symbols (↻ ⊘ ✎ ✦ ✶) takes them from its fallback face. With the WebGL renderer
each glyph is drawn into its own cell, so a second face can't drift the grid
(xsofy saw drift mixing faces under the DOM renderer).

The subset is derived from what the game renders, so it can't go stale: every
non-ASCII literal in main.lg, tesserae/**/*.lg and levels/**, plus printable
ASCII and the full quadrant and sextant ranges (gfx.lg builds those glyphs from
code points, not literals). A glyph that neither a face nor its fallback has is
an error.

Faces are renamed ("Tess Mono", "Tess Plain", ...): the OFL reserves the original
names for unmodified fonts, and a subset is a modified version. Unscii is the
public-domain unscii-16, not unscii-16-full, which is GPL.

Sources aren't vendored: they're downloaded from pinned releases, checksum-
verified, and cached in tools/fonts/.cache/ (gitignored). The committed
artifact is the base64 in the shell. Licences: tools/fonts/.

    uv run --with fonttools --with brotli python3 tools/gen-terminal-font.py \
        [--shell PATH]

--shell can point at a built index.html, to compare faces without rebuilding.
Prior art: xsofy's tools/gen-terminal-font.py (Fairfax HD, one face).
"""
import argparse, base64, hashlib, io, pathlib, re, subprocess, sys, tempfile, urllib.request, zipfile

from fontTools.ttLib import TTFont

SOURCES = {
    "cascadia": dict(
        url="https://github.com/microsoft/cascadia-code/releases/download/v2407.24/CascadiaCode-2407.24.zip",
        sha256="e67a68ee3386db63f48b9054bd196ea752bc6a4ebb4df35adce6733da50c8474",
        member="ttf/static/CascadiaMono-Regular.ttf", label="Cascadia Mono 2407.24"),
    "dejavu": dict(
        url="https://github.com/dejavu-fonts/dejavu-fonts/releases/download/version_2_37/dejavu-fonts-ttf-2.37.zip",
        sha256="7576310b219e04159d35ff61dd4a4ec4cdba4f35c00e002a136f00e96a908b0a",
        member="dejavu-fonts-ttf-2.37/ttf/DejaVuSansMono.ttf", label="DejaVu Sans Mono 2.37"),
    "fairfax": dict(
        url="https://raw.githubusercontent.com/kreativekorp/open-relay/12f11d0cb969c2a03feb48fd04a6e59a262aa5d9/FairfaxHD/FairfaxHD.ttf",
        sha256="4dde4e244cc525e89c61ef9c62a633e8bb4d5387d36df85374d89c709ec9ecdd",
        member=None, label="Fairfax HD (open-relay 12f11d0)"),
    "iosevka": dict(
        url="https://github.com/be5invis/Iosevka/releases/download/v34.9.0/PkgTTF-IosevkaTerm-34.9.0.zip",
        sha256="1c0b8ac68ca210cc253c1833619d37ed2227d96fbdda0a36231375828b7bd6fb",
        member="IosevkaTerm-Extended.ttf", label="Iosevka Term Extended 34.9.0"),
    "unscii": dict(
        # http: Python can't verify viznut.fi's certificate chain; the pinned sha256 still checks the file.
        url="http://viznut.fi/unscii/unscii-16.ttf",
        sha256="0c889d6026f3bfe6cfa0e73833595678a548ed08dabeb1d71c5ad0fa9b309529",
        member=None, label="Unscii 16 2.1"),
}
# ?font=<key> -> (source, fallback source, family). The shell's FACES table names
# the same families; main() checks they match.
FACES = {
    "cascadia": ("cascadia", "dejavu", "Tess Mono"),
    "iosevka": ("iosevka", "dejavu", "Tess Plain"),
    "unscii": ("unscii", "fairfax", "Tess Block"),
    "fairfax": ("fairfax", None, "Tess Fax"),
}

ROOT = pathlib.Path(__file__).resolve().parent.parent
CACHE = ROOT / "tools" / "fonts" / ".cache"
SCAN = ["main.lg", "tesserae/**/*.lg", "levels/**/*"]
ALWAYS = set(range(0x20, 0x7F)) | set(range(0x2580, 0x25A0))
SEXTANTS = set(range(0x1FB00, 0x1FB3C))
BEGIN, END = "/* tess-font:begin (generated by tools/gen-terminal-font.py) */", "/* tess-font:end */"


def fetch(key: str) -> bytes:
    s = SOURCES[key]
    path = CACHE / pathlib.PurePosixPath(s["url"]).name
    if not (path.exists() and hashlib.sha256(path.read_bytes()).hexdigest() == s["sha256"]):
        CACHE.mkdir(parents=True, exist_ok=True)
        print(f"downloading {s['label']}…")
        data = urllib.request.urlopen(s["url"], timeout=120).read()
        got = hashlib.sha256(data).hexdigest()
        if got != s["sha256"]:
            sys.exit(f"checksum mismatch for {s['url']}: expected {s['sha256']}, got {got}")
        path.write_bytes(data)
    data = path.read_bytes()
    return zipfile.ZipFile(io.BytesIO(data)).read(s["member"]) if s["member"] else data


def scan_codepoints() -> set[int]:
    cps = set()
    for pat in SCAN:
        for p in ROOT.glob(pat):
            if p.is_file():
                cps |= {ord(c) for c in p.read_text(errors="replace") if ord(c) > 0x7E}
    cps.discard(0xFFFD)
    return cps


def subset(ttf: bytes, cps: set[int], family: str) -> bytes:
    with tempfile.TemporaryDirectory() as d:
        src, out = pathlib.Path(d, "src.ttf"), pathlib.Path(d, "out.woff2")
        src.write_bytes(ttf)
        subprocess.run(["pyftsubset", str(src), "--unicodes=" + ",".join(f"U+{c:04X}" for c in sorted(cps)),
                        # 13/14 carry the licence, which the OFL and the DejaVu licence
                        # require to travel with the font; pyftsubset drops them by default.
                        "--name-IDs=0,1,2,3,4,5,6,13,14",
                        "--flavor=woff2", f"--output-file={out}"], check=True)
        f = TTFont(out)
    ps = family.replace(" ", "") + "-Regular"
    for rec in f["name"].names:
        if rec.nameID in (1, 16):
            rec.string = family
        elif rec.nameID in (3, 4):
            rec.string = family if rec.nameID == 4 else ps
        elif rec.nameID == 6:
            rec.string = ps
    buf = io.BytesIO()
    f.flavor = "woff2"
    f.save(buf)
    return buf.getvalue()


def face(family: str, woff2: bytes) -> str:
    b64 = base64.b64encode(woff2).decode()
    return (f"@font-face {{ font-family: '{family}'; font-style: normal; font-weight: 400; "
            f"font-display: block;\n  src: url(data:font/woff2;base64,{b64}) format('woff2'); }}")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--shell", type=pathlib.Path, default=ROOT / "web" / "shell.html")
    a = ap.parse_args()

    want = ALWAYS | scan_codepoints() | SEXTANTS
    faces, notes = [], []
    for key, (src, fb_src, family) in FACES.items():
        prim = fetch(src)
        have = set(TTFont(io.BytesIO(prim)).getBestCmap())
        faces.append(face(family, subset(prim, want & have, family)))
        gap = want - have
        fb = fetch(fb_src) if gap and fb_src else None
        missing = gap - (set(TTFont(io.BytesIO(fb)).getBestCmap()) if fb else set())
        if missing:
            sys.exit(f"{key}: no face has " + " ".join(f"U+{c:04X}" for c in sorted(missing)))
        note = f"{key}: {SOURCES[src]['label']}, {len(want & have)} glyphs"
        if gap:
            faces.append(face(family + " Fallback", subset(fb, gap, family + " Fallback")))
            note += f"; {SOURCES[fb_src]['label']}: " + " ".join(chr(c) for c in sorted(gap))
        notes.append(note)

    block = f"{BEGIN}\n" + "".join(f"/* {n} */\n" for n in notes) + "\n".join(faces) + f"\n{END}"
    html = a.shell.read_text()
    for key, (_, _, family) in FACES.items():
        if f"{key}: '{family}'" not in html:
            sys.exit(f"{a.shell}: its FACES table has no {key}: '{family}'")
    html, n = re.subn(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: block, html, flags=re.S)
    if n != 1:
        sys.exit(f"expected one tess-font block in {a.shell}, found {n}")
    a.shell.write_text(html)
    print(f"wrote {a.shell}: {len(block):,} B of @font-face")
    for n in notes:
        print("  " + n)


if __name__ == "__main__":
    main()
